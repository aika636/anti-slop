import test from 'node:test';
import assert from 'node:assert/strict';
import { stemRu } from '../core/stemmer-ru.mjs';

// Ответы посчитаны по эталонному описанию алгоритма Snowball вручную.
const CASES = [
  // существительные
  ['вагоне', 'вагон'], ['вагоны', 'вагон'], ['вагонов', 'вагон'],
  ['голос', 'голос'], ['голоса', 'голос'], ['голосом', 'голос'],
  ['рука', 'рук'], ['руки', 'рук'], ['рукой', 'рук'], ['руках', 'рук'],
  // прилагательные
  ['красивый', 'красив'], ['красивая', 'красив'], ['красивого', 'красив'],
  ['серебристые', 'серебрист'], ['серебристых', 'серебрист'],
  // причастия
  ['читающий', 'чита'], ['прочитанный', 'прочита'],
  // глаголы
  ['смотрел', 'смотрел'], ['смотрела', 'смотрел'], ['смотрели', 'смотрел'],
  ['посмотрел', 'посмотрел'],
  ['говорить', 'говор'], ['говорит', 'говор'], ['говорил', 'говор'],
  // возвратность
  ['улыбнулся', 'улыбнул'], ['улыбнулась', 'улыбнул'],
  // деепричастия
  // «посмотрев» уходит по существительному «-ев», а не по деепричастию:
  // группа 1 требует «а»/«я» перед «в». Это поведение эталона, не ошибка порта.
  ['сказав', 'сказа'], ['посмотрев', 'посмотр'],
  // словообразование и превосходная степень
  // «-ость» снимается только внутри R2; в коротком «нежность» R2 начинается
  // позже окончания, поэтому остаётся «нежност» — так же, как в эталоне.
  ['нежность', 'нежност'], ['удивительность', 'удивительн'],
  ['красивейший', 'красив'],
  // короткие слова не трогаем
  ['он', 'он'], ['и', 'и'], ['её', 'её'],
];

test('стеммер сводит формы к одной основе', () => {
  for (const [word, expected] of CASES) {
    assert.equal(stemRu(word), expected, `${word} → ${stemRu(word)}, ожидалось ${expected}`);
  }
});

test('варианты одного оборота склеиваются', () => {
  // Ради этого стемминг и включён по умолчанию.
  const a = ['серебристые', 'глаза', 'сузились'].map(stemRu).join(' ');
  const b = ['серебристых', 'глаз', 'сузилась'].map(stemRu).join(' ');
  assert.equal(a, b);
});

test('беглая гласная стеммеру не поддаётся — материал для списка исключений', () => {
  // Известная слабость Snowball: чередование в корне не сводится.
  // Такие пары — ровно то, ради чего в tokenize.mjs заведён STEM_EXCEPTIONS.
  assert.notEqual(stemRu('холодок'), stemRu('холодка'));
});

test('основа не длиннее слова и не пустая', () => {
  // Идемпотентности у Snowball нет и не должно быть: «красивый» → «красив»,
  // а «красив» сам по себе выглядит как деепричастие и режется дальше.
  // Гарантия слабее, но нужна: пустой ключ обвалил бы таблицу частот.
  for (const [word] of CASES) {
    const s = stemRu(word);
    assert.ok(s.length > 0, `пустая основа для «${word}»`);
    assert.ok(s.length <= word.length, `основа длиннее слова для «${word}»`);
    assert.ok(word.startsWith(s), `основа не префикс слова для «${word}»`);
  }
});
