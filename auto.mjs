/**
 * auto — когда расширение вправе посчитать чат само, без нажатия кнопки.
 *
 * Половина «фоновой работы» была здесь с самого начала: `MESSAGE_RECEIVED`
 * досчитывает новый ответ в живую сессию, и пока чат просто продолжается,
 * пересчитывать нечего — числа и так точные. Кнопка нужна ровно в трёх случаях,
 * когда досчитать физически нельзя:
 *
 * 1. чата ещё не считали — сессии нет и итога нет;
 * 2. итог приехал из кеша прошлого сеанса — сессии за ним не стоит, и первый же
 *    новый ответ помечает числа устаревшими;
 * 3. правка, удаление или свайп — из накопительного счётчика старый текст не
 *    вычесть, нужен полный проход.
 *
 * Эта настройка закрывает именно их. **Число в ней — дроссель, а не
 * расписание.** «Считать каждые N ответов» звучало бы понятнее, но означало бы
 * полный проход по чату там, где досчёт даёт те же самые числа даром: на чате в
 * 166 тысяч слов проход стоит около 1274 мс работы воркера (`tools/bench`), и
 * платить их за уже известный ответ незачем. Поэтому N отвечает не на вопрос
 * «как часто считать», а на вопрос «как часто МОЖНО»: между двумя полными
 * проходами должно пройти столько ответов модели. Правка в длинном чате не
 * запускает проход на каждое сообщение, а числа догоняют чат сами.
 *
 * Модуль чистый: состояние живёт в `index.js`, здесь только правило.
 */

/** Умолчание дросселя. Пять ответов — примерно одна сцена: реже уже заметно, что числа отстают. */
export const AUTO_EVERY_DEFAULT = 5;
export const AUTO_EVERY_MIN = 1;
export const AUTO_EVERY_MAX = 100;

/**
 * Пора ли считать самому.
 *
 * @param {object} s снимок состояния
 * @param {boolean} s.enabled галочка в настройках
 * @param {number} s.every дроссель: сколько ответов должно пройти между проходами
 * @param {number} s.since сколько ответов модели прошло с последнего полного прохода
 *   (`Infinity` — с открытия чата ни одного прохода не было, ждать нечего)
 * @param {boolean} s.chatOpen открыт ли вообще чат
 * @param {boolean} s.busy подсчёт уже идёт
 * @param {boolean} s.hasSession жива ли сессия, в которую можно досчитывать
 * @param {boolean} s.hasResult есть ли показанные числа
 * @param {boolean} s.dirty числа устарели: правка, удаление, свайп
 * @returns {boolean}
 */
export function shouldAutoCount(s) {
    if (!s?.enabled || !s.chatOpen || s.busy) return false;

    // Сессия жива и чат не менялся задним числом — новый ответ досчитается сам,
    // и полный проход дал бы ровно те же числа за секунды работы.
    const needs = s.dirty || (!s.hasSession && !s.hasResult);
    if (!needs) return false;

    // Итог из кеша, за которым нет сессии, сюда не попадает: числа верные, и
    // тратить проход на открытии длинного чата не за что. Он станет `dirty` от
    // первого же нового ответа — вот тогда проход и оправдан.

    const every = Math.max(AUTO_EVERY_MIN, Math.round(Number(s.every) || AUTO_EVERY_DEFAULT));
    return (s.since ?? 0) >= every;
}
