// core/index — сводный индекс слопа: одно число 0–100 на сообщение и на чат.
//
// Собирает вместе три
// уже посчитанных величины: покрытие повторами (`ngrams`), лексическое
// разнообразие (`diversity`) и близость к предыдущим сообщениям (`similarity`).
//
// Три требования, из которых вытекает вся конструкция.
//
// 1. **Сопоставимость.** Цифра нужна, чтобы сравнить чат с собой во времени и
//    один пресет с другим. Поэтому нормировка идёт по ФИКСИРОВАННЫМ якорям, а
//    не по распределению внутри текущего чата: нормировка по своему же чату
//    даёт красивую шкалу и полностью убивает сравнимость — в любом чате
//    найдётся своё худшее сообщение, и оно всегда получит сотню.
// 2. **Независимость от длины.** Все три компонента — доли, а не суммы. Иначе
//    индекс мерил бы многословность вместо штампованности.
// 3. **Версионирование.** Формула меняется — старые значения несравнимы. Версия
//    хранится рядом с числом, кеш по ней обесценивается.
//
// **Формула черновая, и это её штатное состояние.** Веса и якоря
// нельзя откалибровать без набора чатов, размеченных человеком на «хороший» и
// «плохой»; таких чатов нет и до релиза не будет. Пока их нет, задача формулы
// скромнее: не перепутать заведомо разное. Поэтому `draft` в ответе стоит всегда,
// когда прозы меньше `DRAFT_UNTIL_WORDS`, а сами якоря вынесены в одну таблицу
// сверху — чтобы калибровка была правкой пяти чисел, а не переписыванием.

import { MATTR_WINDOW } from './diversity.mjs';

/**
 * Версия формулы. Меняется при любой правке весов, якорей или состава
 * компонентов. Хранится вместе с посчитанным индексом; несовпадение версии
 * означает «эти два числа сравнивать нельзя».
 */
export const FORMULA_VERSION = '0.1-draft';

/**
 * Объём прозы, до которого индекс помечается черновым в любом случае.
 * Та же граница, что и у переключения счётчика: на коротком чате
 * почти всё — одиночки, повторам просто неоткуда взяться, и низкий индекс
 * говорит о длине чата, а не о качестве текста.
 */
export const DRAFT_UNTIL_WORDS = 50_000;

/**
 * Якоря нормировки: значение компонента, дающее 0 баллов, и значение, дающее
 * 100. Между ними — линейно, за пределами — обрезается.
 *
 * Откуда взяты. Из распределения по 142 сообщениям корпуса разработки
 * (`tools/calibrate.mjs`, замер 10 августа 2026):
 *
 *   покрытие     p10 4,3%   p50 17,8%   p90 25,0%   максимум 32,4%
 *   MATTR        p10 82,0%  p50 86,4%   p90 88,8%   максимум 90,3%
 *   похожесть    p10 0,19%  p50 0,82%   p90 2,34%   максимум 5,14%
 *
 * Правило простое: «ноль баллов» ставится примерно на десятый процентиль, то
 * есть на лучшее, что реально встречается, а «сто баллов» — ЗА наблюдаемым
 * максимумом. Второе важнее первого: якорь на максимуме означал бы, что первый
 * же чат похуже упрётся в потолок и перестанет отличаться от следующего. Запас
 * оставлен намеренно — этот корпус написан одной моделью с одним пресетом, и
 * заведомо более штампованный текст существует.
 *
 * По похожести цифры сходятся с независимым замером: пол по всем
 * парам 0,13%, верхние 5% — 3,1%, худшая пара корпуса — 5,1%.
 *
 * **Это одна точка, а не «нормальные значения русского РП».** Якоря переедут,
 * как только появится второй пресет для сравнения, и версия формулы вместе с
 * ними — иначе старые числа молча станут несравнимыми с новыми.
 */
export const ANCHORS = {
  coverage: { zero: 0.05, full: 0.40 },
  diversity: { zero: 0.90, full: 0.75 },   // перевёрнут: чем МЕНЬШЕ MATTR, тем хуже
  similarity: { zero: 0.0015, full: 0.06 },
};

/**
 * Веса компонентов. «Покрытие повторами — основной, разнообразие и близость к
 * предыдущим — средние». Задуманный четвёртым словарь клише
 * пока отсутствует, поэтому в сумме здесь три слагаемых, а не
 * четыре, и добавление четвёртого будет сменой версии формулы.
 */
export const WEIGHTS = { coverage: 0.5, diversity: 0.25, similarity: 0.25 };

/** Линейная нормировка по якорям с обрезкой. Направление задаётся якорями. */
function scale(value, { zero, full }) {
  if (!Number.isFinite(value)) return 0;
  const t = (value - zero) / (full - zero);
  return Math.max(0, Math.min(1, t));
}

/**
 * Индекс одного сообщения.
 *
 * Все три компонента считаются ПРОТИВ СОСТОЯНИЯ ДО ЭТОГО СООБЩЕНИЯ — иначе
 * сообщение окажется повторяющим само себя. За это
 * отвечает вызывающий: `coverage` берётся из `counter.coverage(segments)` до
 * `counter.add`, `similarity` — из `detector.add`, который сравнивает только с
 * ранее добавленными.
 *
 * @param {{coverage: number, mattr: number, similarity: number, words: number}} parts
 *   `coverage` — доля слов сообщения, накрытых уже известными оборотами, 0..1;
 *   `mattr` — MATTR этого сообщения, 0..1;
 *   `similarity` — containment к самому похожему из предыдущих, 0..1.
 * @returns {{value: number, parts: object, version: string, draft: boolean}}
 *   `value` — 0..100, целое.
 */
export function messageIndex({ coverage = 0, mattr = NaN, similarity = 0, words = 0 } = {}) {
  const scaled = {
    coverage: scale(coverage, ANCHORS.coverage),
    diversity: scale(mattr, ANCHORS.diversity),
    similarity: scale(similarity, ANCHORS.similarity),
  };

  // Сообщение короче окна MATTR: разнообразие на нём не меряется честно, и
  // подставлять ноль нельзя — это выдало бы «идеальное разнообразие» за счёт
  // короткого текста. Компонент выбрасывается, веса оставшихся нормируются.
  const usable = Object.keys(WEIGHTS).filter(
    k => !(k === 'diversity' && !(words >= MATTR_WINDOW && Number.isFinite(mattr))),
  );
  let sum = 0, weight = 0;
  for (const k of usable) { sum += scaled[k] * WEIGHTS[k]; weight += WEIGHTS[k]; }

  return {
    value: Math.round((weight > 0 ? sum / weight : 0) * 100),
    parts: scaled,
    version: FORMULA_VERSION,
    draft: true,
  };
}

/**
 * Индекс чата — среднее по сообщениям, взвешенное по длине.
 *
 * Именно взвешенное: простое среднее уравнивает реплику в двадцать слов с
 * ходом на две тысячи, а вклад в ощущение «модель скатилась в шаблон» у них
 * разный. Вес по словам — это «индекс на слово текста», и он не зависит от
 * того, нарезан чат крупно или мелко.
 *
 * @param {Array<{value: number, words: number}>} messages
 */
export function chatIndex(messages = [], { words = null } = {}) {
  let sum = 0, weight = 0;
  for (const m of messages) {
    // Сообщение без прозы (одна разметка, инфоблок, промпт картинки) в среднее
    // не входит вообще. Дать ему вес единицы — значит подмешать в индекс чата
    // гарантированный ноль: покрытия и похожести там нет по устройству, а не
    // потому, что текст свежий. У пользователя с инфоблоком каждый ход таких
    // сообщений может быть половина, и индекс окажется занижен вдвое.
    const w = m.words ?? 0;
    if (w <= 0) continue;
    sum += m.value * w;
    weight += w;
  }
  // Запасной путь: ни у одного сообщения нет длины. Тогда взвешивать нечем, и
  // считается простое среднее — это лучше нуля, который выглядел бы как
  // посчитанный ответ «повторов нет». Смешанный случай (у части сообщений
  // длина есть) сюда не попадает: там сообщения без прозы просто не в счёт.
  if (weight === 0 && messages.length) {
    for (const m of messages) sum += m.value;
    weight = messages.length;
  }

  const totalWords = words ?? weight;
  return {
    value: weight > 0 ? Math.round(sum / weight) : 0,
    messages: messages.length,
    words: totalWords,
    version: FORMULA_VERSION,
    // Черновым помечается всё, что посчитано на объёме, где повторам ещё
    // неоткуда взяться. Это не оговорка для порядка: на 20 тысячах слов
    // покрытие занижено механически, а не потому, что текст хорош.
    draft: totalWords < DRAFT_UNTIL_WORDS,
  };
}
