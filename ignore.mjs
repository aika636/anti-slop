/**
 * ignore — обороты, которые пользователь велел не считать.
 *
 * Зачем это вообще нужно. Отделение прозы (`core/strip`) — эвристика, и она по
 * устройству не может быть полной: у каждого второго пресета свой инфоблок,
 * своя подпись под картинкой, свой титул персонажа. Всё это повторяется потому,
 * что так устроен пресет, а не потому, что модель скатилась в шаблон, и в топе
 * оно бесполезно. Игнор-лист — ручная доводка там, где эвристика промахнулась.
 *
 * **Ключ — основы, а не показанная строка.** Оборот «по спине пробежал холодок»
 * встречается в чате и как «по спине пробежала дрожь»: скрыв одну живую форму,
 * пользователь ждёт, что уйдут все её варианты, а не что завтра всплывёт тот же
 * оборот в другом падеже. Строка остаётся рядом с ключом — но только чтобы было
 * что показать в списке скрытых.
 *
 * Список общий на все чаты, а не на текущий: инфоблок пресета одинаков во всех
 * чатах этого пресета, и заставлять скрывать его в каждом заново — издевательство.
 *
 * Модуль чистый: где лежит список, знает `index.js`, здесь только правила.
 */

/**
 * Ключ оборота.
 *
 * Основы — если они есть. Кеш их тоже хранит (см. `trim` в `storage.js`), так
 * что после перезагрузки вкладки ключи не разъезжаются с теми, что записаны в
 * настройках. Отката на строку хватает для чужих данных: импортированный список
 * основ не несёт.
 */
export function phraseKey(item) {
    const stems = item?.stems;
    if (Array.isArray(stems) && stems.length) return stems.join(' ');
    return String(item?.text ?? '').trim().toLowerCase();
}

/** Запись для настроек: ключ плюс то, что показать в списке скрытых. */
export function ignoreEntry(item) {
    return { key: phraseKey(item), text: (item?.text ?? '').trim() || phraseKey(item) };
}

/**
 * Разделить топ на видимое и скрытое.
 *
 * Скрытое не выбрасывается, а возвращается отдельно: иначе пользователь, скрывший
 * оборот по ошибке, не сможет найти его обратно — в топ он больше не попадёт
 * никогда, а в настройках увидит только строку без чисел.
 *
 * Итог не изменяется на месте: те же данные показывает график, отдаёт карточка и
 * сохраняет кеш, и подменять их отфильтрованными нельзя — иначе скрытый оборот
 * исчезнет и из сохранённого подсчёта, то есть навсегда.
 *
 * @param {{top?: Array<object>}} result
 * @param {Iterable<string>} keys ключи скрытых оборотов
 */
export function splitIgnored(result, keys) {
    const set = keys instanceof Set ? keys : new Set(keys ?? []);
    const top = [], hidden = [];
    for (const item of result?.top ?? []) {
        (set.has(phraseKey(item)) ? hidden : top).push(item);
    }
    return { top, hidden };
}

/**
 * Копия итога с отфильтрованным топом — то, что уходит в панель, в промпт и в
 * карточку. Всё остальное в итоге остаётся нетронутым.
 */
export function withoutIgnored(result, keys) {
    if (!result) return result;
    const { top } = splitIgnored(result, keys);
    return top.length === (result.top?.length ?? 0) ? result : { ...result, top };
}
