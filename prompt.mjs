/**
 * prompt — сборка негатив-инструкции из найденных оборотов.
 *
 * Главное решение модуля: **отдаётся правило, а не перечень.** Причина не
 * теоретическая. Автор пресетов из сцены сформулировала её так: «оставлять
 * просто бан лист модельке без него — отдать ей список вкусностей в буквальном
 * смысле». Перечислив фразу, ты её же и подсказал; рабочий обход, найденный
 * сценой опытным путём, — правило замены. Поэтому по умолчанию здесь блок
 * правила, а голый список остаётся отдельным режимом для тех, кто знает, что
 * делает.
 *
 * **Правило не опирается на блок размышлений, и это исправление по замеру.**
 * Прежняя формулировка начиналась словами «в размышлениях перед ответом сверь
 * черновик»; на модели без блока размышлений — а таких половина среди тех, на
 * которых расширение включат, — такая инструкция неисполнима в принципе.
 * «Прежде чем писать» работает и там, и там, а думающая модель всё равно
 * разберёт это в размышлениях, потому что она так устроена.
 *
 * Модуль чистый: ни таверны, ни браузера, ни настроек — на вход обороты и
 * шаблон, на выход строка. Так его можно прогнать тестом на Node, а вставку в
 * промпт оставить `index.js`.
 *
 * Показываются ЖИВЫЕ ФОРМЫ (`text`), а не основы: «пользователю
 * никогда не показывается основа». Модели — тем более: основа «холодок пробеж»
 * в правиле выглядит как опечатка и учит модель ровно не тому.
 */

/**
 * Шаблоны по умолчанию. Редактируются пользователем (у
 * разных авторов пресетов разные конвенции оформления), поэтому здесь только
 * начальное значение, а не константа поведения.
 *
 * Формулировка от обратного: не «не пиши так», а что
 * делать вместо. И оговорка, что список — это не запретные слова: без неё модель
 * читает его как чёрный список и начинает избегать самих слов, а не штампа.
 */
export const DEFAULT_TEMPLATES = {
    ru: {
        rule: `<повторы>
Прежде чем писать ответ, сверь задуманное со списком ниже. Оборот из списка,
который просится в текст, замени: скажи то же самое через конкретное действие,
деталь обстановки или телесное ощущение, а не готовой формулой.
Это не запретные слова, а места, где текст этого чата уже стёрся от повторения.
Стёршиеся обороты ({{count}}): {{phrases}}
</повторы>`,
        list: `Не используй следующие обороты: {{phrases}}`,
    },
    en: {
        rule: `<repetition>
Before you write, check what you are about to say against the list below. Replace
any phrase from the list that wants into your reply: say the same thing through a
concrete action, a detail of the setting or a bodily sensation instead of a ready
formula.
These are not forbidden words — they are the spots where this chat has worn thin.
Worn-out phrases ({{count}}): {{phrases}}
</repetition>`,
        list: `Do not use the following phrases: {{phrases}}`,
    },
};

/** Шаблон по умолчанию, с откатом на русский: он исходный. */
export function defaultTemplate(format = 'rule', locale = 'ru') {
    const table = DEFAULT_TEMPLATES[locale] ?? DEFAULT_TEMPLATES.ru;
    return table[format] ?? table.rule;
}

/**
 * Сколько сообщений назад оборот считается ещё идущим.
 *
 * Отбор в правило по одному C-value берёт исторических чемпионов: вес
 * накопительный и не убывает, поэтому оборот, отгремевший в начале чата и с тех
 * пор не встреченный, занимает строку в каждом запросе — за токены и без
 * пользы. Свежесть смотрит на `lastMessage`, который в записи оборота уже есть.
 *
 * Тридцать — того же порядка, что `MIN_SPAN` темпа (двадцать) и окно панели:
 * это «последние несколько сцен», а не «последние два ответа».
 */
export const FRESH_SPAN = 30;

/**
 * Ротация хвоста: сколько мест из `limit` отдаётся сменным оборотам и как редко
 * они меняются.
 *
 * Зачем. Список каждый ход один и тот же, и модель к нему приспосабливается —
 * уходит в смежный штамп («холодок по спине» → «мурашки по спине»), а список
 * этого не замечает, потому что не менялся. Две сменные позиции делают сетку
 * мельче: в неё попадает то, куда модель убегает.
 *
 * **Шаг ротации редкий, и это не украшательство.** Блок правила стоит в начале
 * контекста, то есть меняющийся блок — это меняющийся префикс, а по нему на
 * стороне API живёт кеш промпта. Меняя список каждый ход, мы обнуляли бы кеш
 * каждым запросом и платили бы за ротацию деньгами. Раз в `ROTATE_EVERY`
 * сообщений — это один сброс кеша на десяток ответов.
 *
 * Ускорять шаг нельзя, не ответив сначала на вопрос про кеш.
 */
export const ROTATE_SLOTS = 2;
export const ROTATE_EVERY = 10;

/** Докуда тянется пул сменных оборотов: ранги от `limit − ROTATE_SLOTS + 1` до этого. */
export const ROTATE_POOL = 20;

/** Затих ли оборот по знаку темпа. Молчание темпа — это «идёт как шёл». */
function isQuiet(trend) {
    if (!trend) return false;
    // `slower` без `stopped` — оборот, который стал реже, но продолжается; ему в
    // правиле место. Затих — это `cooled` (выпал из собственного ритма) и
    // `slower`, у которого после якоря не было ни одного вхождения.
    return trend.kind === 'cooled' || (trend.kind === 'slower' && trend.stopped);
}

/**
 * Обороты для промпта: верхушка топа, уже без скрытых.
 *
 * Базовый порядок — C-value, тот же, что в панели: пользователь должен видеть в
 * промпте то же, что в списке. Пустые строки отбрасываются — оборот без
 * восстановленной живой формы в правило не годится.
 *
 * Поверх базового порядка три правила, каждое работает и без двух других, и все
 * три включаются только тем, что вызывающий передал нужные данные. Без `opts`
 * функция ведёт себя ровно как раньше — на этом держится `buildList`, где
 * никакой фильтрации быть не должно: там не промпт, а данные.
 *
 * 1. **Затихшие не кладутся.** Отличать затихший оборот от идущего умеет
 *    `trend.mjs`, и его знак уже рисуется стрелкой в списке. Освободившиеся
 *    места отдаются следующим по порядку, а не пропадают.
 * 2. **Свежие вперёд.** Оборот, встреченный в последних `FRESH_SPAN`
 *    сообщениях, для правила важнее набравшего массу в начале чата. Порядок
 *    внутри каждой из двух групп остаётся прежним — по C-value.
 * 3. **Хвост ротируется.** Последние `ROTATE_SLOTS` мест по кругу отдаются
 *    оборотам из пула за пределами верхушки.
 *
 * Знание о темпе приходит СНАРУЖИ функцией, а не импортом `trend.mjs`: сам знак
 * требует якоря, а якорь лежит в хранилище браузера, и модуль, который его
 * запрашивает, перестаёт быть чистым — тест на Node потянул бы за собой
 * `storage.js`. Здесь на вход приходит готовое «затих или нет».
 *
 * @param {Array<{text?: string, stems?: string[], count?: number, cvalue?: number,
 *                lastMessage?: number, n?: number}>} top
 * @param {number} limit
 * @param {{lastIndex?: number, trend?: (item: object) => (object|null),
 *          rotate?: boolean}} [opts]
 *   `lastIndex` — номер последнего сообщения чата; без него свежесть и ротация
 *   не считаются и молча не применяются;
 *   `trend` — знак темпа по обороту (обычно `item => phraseTrend(item, ctx)`).
 */
export function pickPhrases(top, limit = 8, opts = {}) {
    const { lastIndex = NaN, trend = null, rotate = false } = opts;

    const eligible = [];
    const seen = new Set();
    for (const item of top ?? []) {
        const text = (item?.text ?? '').trim();
        if (!text) continue;
        const key = text.toLowerCase();
        if (seen.has(key)) continue;
        seen.add(key);
        if (trend && isQuiet(trend(item))) continue;
        eligible.push(item);
    }

    if (Number.isFinite(lastIndex)) {
        // Устойчивая сортировка: внутри каждой группы порядок остаётся тот, в
        // котором обороты пришли из топа, то есть по C-value.
        const fresh = it => Number.isFinite(it.lastMessage) && lastIndex - it.lastMessage <= FRESH_SPAN;
        eligible.sort((a, b) => (fresh(b) === true) - (fresh(a) === true));
    }

    if (!rotate || !Number.isFinite(lastIndex) || limit <= ROTATE_SLOTS) {
        return eligible.slice(0, limit);
    }

    // Голова стоит на месте, хвост идёт по кругу. Пул — всё, что не попало в
    // голову, вплоть до `ROTATE_POOL`: обороты рангом сразу за головой иначе не
    // попадали бы в правило никогда, хотя от следующих за ними ничем не хуже.
    const head = eligible.slice(0, limit - ROTATE_SLOTS);
    const pool = eligible.slice(limit - ROTATE_SLOTS, ROTATE_POOL);
    if (pool.length <= ROTATE_SLOTS) return eligible.slice(0, limit);

    const step = Math.floor(lastIndex / ROTATE_EVERY);
    const tail = [];
    for (let i = 0; i < ROTATE_SLOTS; i++) {
        tail.push(pool[(step * ROTATE_SLOTS + i) % pool.length]);
    }
    return [...head, ...tail];
}

/**
 * Попадание правила: сколько оборотов из отданного списка встретилось в
 * последних `span` сообщениях.
 *
 * Это **не** «антислоп помог» и не может им быть: расширение не знает, что было
 * бы без правила, и оборот затихает по десятку причин. Это прямое наблюдение —
 * список известен, и известно, что модель написала после, — и оно единственное
 * отвечает на вопрос, стоит ли вставка своих токенов. Формулировки в интерфейсе
 * обязаны остаться описательными, как у знака темпа.
 *
 * @returns {{hits: number, total: number, span: number}|null} `null`, когда
 *   считать не из чего: нет списка или неизвестен номер последнего сообщения.
 */
export function promptHits(phrases, { lastIndex = NaN, span = FRESH_SPAN } = {}) {
    if (!phrases?.length || !Number.isFinite(lastIndex)) return null;
    const hits = phrases.filter(
        p => Number.isFinite(p?.lastMessage) && lastIndex - p.lastMessage <= span).length;
    return { hits, total: phrases.length, span };
}

/**
 * Подставить обороты в шаблон.
 *
 * Три подстановки, и все три нужны разным людям: `{{phrases}}` — через запятую,
 * как в правиле; `{{list}}` — по строкам, для тех, кто оформляет списком;
 * `{{count}}` — число, чтобы модель понимала масштаб, а не думала, что перед ней
 * весь запретный словарь языка.
 *
 * Если оборотов нет — возвращается пустая строка, и вставлять в промпт нечего.
 * Шаблон с пустым `{{phrases}}` был бы хуже отсутствия правила: модель получила
 * бы указание сверяться с пустым списком.
 */
export function fillTemplate(template, phrases) {
    if (!phrases.length) return '';
    const texts = phrases.map(p => p.text.trim());
    return String(template ?? '')
        .replaceAll('{{phrases}}', texts.join(', '))
        .replaceAll('{{list}}', texts.map(x => '- ' + x).join('\n'))
        .replaceAll('{{count}}', String(texts.length))
        .trim();
}

/**
 * Готовый текст для вставки в промпт.
 *
 * @param {{top?: Array<object>}} result итог анализа (уже без скрытых оборотов)
 * @param {{format?: 'rule'|'list', template?: string, limit?: number, locale?: string,
 *          lastIndex?: number, trend?: (item: object) => (object|null), rotate?: boolean}} [opts]
 *   последние три — отбор по свежести, отсев затихших и ротация хвоста, см.
 *   `pickPhrases`. Без них правило собирается по одному C-value, как раньше.
 * @returns {string} пустая строка, если вставлять нечего
 */
export function buildPrompt(result, opts = {}) {
    return promptParts(result, opts).text;
}

/**
 * То же, что `buildPrompt`, но с самим списком оборотов рядом.
 *
 * Нужна там, где текст и список нужны оба: панель показывает попадание правила
 * (`promptHits`) по тому же списку, который уехал в промпт. Собирать его вторым
 * вызовом было бы не просто лишней работой — при ротации второй вызов в другую
 * секунду может вернуть другой набор, и показанное разошлось бы с отданным.
 */
export function promptParts(result, opts = {}) {
    const { format = 'rule', limit = 8, locale = 'ru', lastIndex, trend, rotate } = opts;
    const template = opts.template || defaultTemplate(format, locale);
    const phrases = pickPhrases(result?.top, limit, { lastIndex, trend, rotate });
    return { text: fillTemplate(template, phrases), phrases };
}

/**
 * Голый список оборотов по строкам — для буфера обмена и чужих полей ввода.
 *
 * Отдельно от `buildPrompt`: это не промпт, а данные, и обёртка правилом здесь
 * только мешала бы.
 */
export function buildList(result, limit = 50) {
    return pickPhrases(result?.top, limit).map(p => p.text.trim()).join('\n');
}
